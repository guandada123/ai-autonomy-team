def build(ws, title, note, headers, rows, widths, fills=None, heights=None):
    """通用建表：标题行 + 说明行 + 表头 + 数据"""
    ncol = len(headers)
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=ncol)
    c = ws.cell(row=1, column=1, value=title)
    c.font = TITLE_FONT
    c.alignment = Alignment(vertical="center")

    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=ncol)
    c = ws.cell(row=2, column=1, value=note)
    c.font = NOTE_FONT
    c.alignment = Alignment(vertical="center", wrap_text=True)

    for j, h in enumerate(headers, start=1):
        c = ws.cell(row=3, column=j, value=h)
        c.font = HDR_FONT
        c.fill = HDR_FILL
        c.alignment = WRAP_C
        c.border = BORDER

    for i, row in enumerate(rows):
        r = 4 + i
        f = ALT_FILL if i % 2 else None
        if fills and i < len(fills) and fills[i]:
            f = fills[i]
        for j, v in enumerate(row, start=1):
            c = ws.cell(row=r, column=j, value=v)
            c.font = BOLD_FONT if j == 1 or (isinstance(v, str) and v.startswith("★")) else BODY_FONT
            c.alignment = WRAP
            c.border = BORDER
            if f:
                c.fill = f
        if heights and i < len(heights) and heights[i]:
            ws.row_dimensions[r].height = heights[i]

    for j, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(j)].width = w
    ws.row_dimensions[1].height = 26
    ws.row_dimensions[2].height = 30
    ws.row_dimensions[3].height = 30
    ws.freeze_panes = "A4"


